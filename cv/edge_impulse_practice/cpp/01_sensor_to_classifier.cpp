// 01_sensor_to_classifier.cpp
//
// HOW SENSOR DATA REACHES AN EDGE IMPULSE MODEL ON A MICROCONTROLLER
// (and where it usually goes wrong for customers)
//
//   sensor (int16 counts) -> convert units -> ring buffer -> every STRIDE:
//   copy last WINDOW into a flat, interleaved float buffer -> signal_t -> run_classifier()
//
// Compile & run on your PC (no board needed):
//   python -m ziglang c++ -std=c++11 -O2 01_sensor_to_classifier.cpp -o 01.exe && 01.exe
//
// Microcontroller habits used here (interviewers like hearing these):
//   - no new/malloc: every buffer is a fixed-size static array (RAM known at compile time)
//   - fixed-width types: int16_t for raw sensor counts, uint32_t for indexes/time
//   - constexpr sizes, so the compiler checks everything fits
//   - the sensor read happens at a FIXED rate (on a real board: a timer interrupt)

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstring>

// ----------------------------------------------------------------------------
// 1. Settings. In a real project these come from model_metadata.h, generated by
//    Edge Impulse: EI_CLASSIFIER_INTERVAL_MS, EI_CLASSIFIER_RAW_SAMPLES_PER_FRAME,
//    EI_CLASSIFIER_RAW_SAMPLE_COUNT, EI_CLASSIFIER_DSP_INPUT_FRAME_SIZE.
// ----------------------------------------------------------------------------
constexpr uint32_t SAMPLE_RATE_HZ = 1000;              // must match the training data!
constexpr uint32_t AXES = 3;                           // ax, ay, az
constexpr uint32_t WINDOW_SAMPLES = 1000;              // 1.0 s window
constexpr uint32_t STRIDE_SAMPLES = 200;               // 0.2 s stride -> 5 answers per second
constexpr uint32_t FRAME_SIZE = WINDOW_SAMPLES * AXES; // = EI_CLASSIFIER_DSP_INPUT_FRAME_SIZE

constexpr float G = 9.80665f;
constexpr float COUNTS_PER_G = 16384.0f;               // 16-bit sensor on the +/-2 g range

// Flip to 1 to reproduce the classic customer bug: model trained on m/s^2, device feeds raw counts.
#define FORGET_UNIT_CONVERSION 0

// ----------------------------------------------------------------------------
// 2. Fake sensor. On a real board this is an I2C/SPI read of the accelerometer
//    registers, returning RAW INTEGER COUNTS, not m/s^2.
// ----------------------------------------------------------------------------
static bool g_fault = false;

static void read_accel_raw(uint32_t n, int16_t out[AXES]) {
    const float t = (float)n / SAMPLE_RATE_HZ;
    float shaft = 0.5f * std::sin(2.0f * 3.14159265f * 50.0f * t);
    float bearing = g_fault ? 0.6f * std::sin(2.0f * 3.14159265f * 300.0f * t) : 0.0f;
    float a[AXES] = {shaft + bearing, 0.6f * shaft + 0.5f * bearing, G + 0.3f * shaft};
    for (uint32_t i = 0; i < AXES; i++) {
        float counts = a[i] / G * COUNTS_PER_G;
        if (counts > 32767.0f) counts = 32767.0f;      // the sensor saturates (clipping)
        if (counts < -32768.0f) counts = -32768.0f;
        out[i] = (int16_t)std::lround(counts);
    }
}

// ----------------------------------------------------------------------------
// 3. Units: convert counts to the SAME units the training data used.
// ----------------------------------------------------------------------------
static inline float counts_to_ms2(int16_t c) {
#if FORGET_UNIT_CONVERSION
    return (float)c;                                   // BUG: model sees numbers ~1,670x too big
#else
    return (float)c / COUNTS_PER_G * G;
#endif
}

// ----------------------------------------------------------------------------
// 4. Ring buffer: always holds the most recent WINDOW_SAMPLES samples.
//    Writing never moves data; only the write index moves (cheap on an MCU).
// ----------------------------------------------------------------------------
static float g_ring[WINDOW_SAMPLES][AXES];
static uint32_t g_write_idx = 0;       // where the next sample goes
static uint32_t g_samples_seen = 0;    // total samples since start-up

static void ring_push(const float s[AXES]) {
    for (uint32_t i = 0; i < AXES; i++) g_ring[g_write_idx][i] = s[i];
    g_write_idx = (g_write_idx + 1) % WINDOW_SAMPLES;
    g_samples_seen++;
}

// ----------------------------------------------------------------------------
// 5. The model input: ONE flat float array, oldest sample first, axes INTERLEAVED:
//      [ax0, ay0, az0, ax1, ay1, az1, ...]
//    This is the same layout as the "Raw features" you can copy in Edge Impulse Studio.
//    Wrong axis order or non-interleaved layout = a very common silent bug.
// ----------------------------------------------------------------------------
static float g_features[FRAME_SIZE];

static void ring_to_features() {
    for (uint32_t k = 0; k < WINDOW_SAMPLES; k++) {
        uint32_t src = (g_write_idx + k) % WINDOW_SAMPLES;   // oldest first
        for (uint32_t i = 0; i < AXES; i++) g_features[k * AXES + i] = g_ring[src][i];
    }
}

// ----------------------------------------------------------------------------
// 6. signal_t: how the Edge Impulse SDK reads your data.
//    The real one lives in edge-impulse-sdk/dsp/numpy_types.h. The SDK does not take
//    your array directly; it calls get_data() to pull chunks, so data could even be
//    streamed from external memory. This mock has the same shape.
// ----------------------------------------------------------------------------
struct mock_signal_t {
    int (*get_data)(size_t offset, size_t length, float *out_ptr);
    size_t total_length;
};

static int features_get_data(size_t offset, size_t length, float *out_ptr) {
    std::memcpy(out_ptr, g_features + offset, length * sizeof(float));
    return 0;
}

// Stand-in for run_classifier(). A real model runs the DSP block + neural network.
// This one just measures vibration energy on X (mean removed), so the data flow is
// the lesson, not the model.
static const char *mock_run_classifier(const mock_signal_t *sig, float *score) {
    static float chunk[AXES * 50];                      // pull data in chunks, like the SDK
    double sum = 0, sum_sq = 0;
    size_t n = 0;
    for (size_t off = 0; off < sig->total_length; off += sizeof(chunk) / sizeof(float)) {
        size_t len = sizeof(chunk) / sizeof(float);
        if (off + len > sig->total_length) len = sig->total_length - off;
        sig->get_data(off, len, chunk);
        for (size_t j = 0; j < len; j += AXES) { sum += chunk[j]; sum_sq += chunk[j] * chunk[j]; n++; }
    }
    double mean = sum / n;
    *score = (float)std::sqrt(sum_sq / n - mean * mean);
    return (*score > 0.48f) ? "fault" : "normal";       // threshold learned "in training"
}

// ----------------------------------------------------------------------------
// 7. Main loop. On a board: a timer interrupt at SAMPLE_RATE_HZ calls the sensor read;
//    the main loop runs the classifier when a new stride's worth of samples is ready.
// ----------------------------------------------------------------------------
int main() {
    std::printf("RAM for ring buffer: %u bytes, feature buffer: %u bytes\n",
                (unsigned)sizeof(g_ring), (unsigned)sizeof(g_features));

    for (uint32_t n = 0; n < 4 * SAMPLE_RATE_HZ; n++) {     // simulate 4 seconds
        g_fault = (n >= 2 * SAMPLE_RATE_HZ);                // bearing starts failing at t = 2 s

        int16_t raw[AXES];
        read_accel_raw(n, raw);
        float s[AXES] = {counts_to_ms2(raw[0]), counts_to_ms2(raw[1]), counts_to_ms2(raw[2])};
        ring_push(s);

        bool window_full = g_samples_seen >= WINDOW_SAMPLES;
        bool stride_due = (g_samples_seen % STRIDE_SAMPLES) == 0;
        if (window_full && stride_due) {
            ring_to_features();
            mock_signal_t sig = {&features_get_data, FRAME_SIZE};
            float score = 0;
            const char *label = mock_run_classifier(&sig, &score);
            std::printf("t=%.1fs  window %.1f-%.1fs  score=%.3f  -> %s\n",
                        (double)g_samples_seen / SAMPLE_RATE_HZ,
                        (double)(g_samples_seen - WINDOW_SAMPLES) / SAMPLE_RATE_HZ,
                        (double)g_samples_seen / SAMPLE_RATE_HZ, score, label);
        }
    }

    // DEBUGGING TRICK (the "Studio says 96%, device fails" checklist):
    // print the exact buffer the model received, paste it into Studio, compare.
    std::printf("\nFirst 2 samples of the last window (ax, ay, az, ax, ay, az):\n");
    for (uint32_t i = 0; i < 2 * AXES; i++) std::printf("%.4f%s", g_features[i], i + 1 < 2 * AXES ? ", " : "\n");
    std::printf("Compare with Studio's raw features: Z should be ~9.8 if units are right.\n");
    return 0;
}

